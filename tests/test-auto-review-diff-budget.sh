# ==============================================================================
# Section 4: Built-in generated-file stripping (lockfiles, snapshots, escapes)
# ==============================================================================
section_4() (
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  fail=0

  hunk() { # $1 = a path, $2 = b path, $3 = body lines
    printf 'diff --git a/%s b/%s\nindex 1111111..2222222 100644\n--- a/%s\n+++ b/%s\n@@ -1 +1,%d @@\n' "$1" "$2" "$1" "$2" "$3"
    local i
    for i in $(seq "$3"); do printf '+line %d\n' "$i"; done
  }

  {
    hunk src/app.ts src/app.ts 2
    hunk src/__snapshots__/Chart.test.tsx.snap src/__snapshots__/Chart.test.tsx.snap 3
    hunk package-lock.json package-lock.json 4
    hunk web/pnpm-lock.yaml web/pnpm-lock.yaml 1
    hunk __snapshots__/root.txt __snapshots__/root.txt 1
    hunk crates/x/Cargo.lock crates/x/Cargo.lock 1
    hunk go.sum go.sum 1
    hunk src/snapshot.ts src/snapshot.ts 1
    hunk docs/yarn.lock.md docs/yarn.lock.md 1
    hunk old/Name.snap src/Name.ts 1
    hunk src/Old.ts src/Old.snap 1
    printf 'diff --git "a/src/a\\tb.snap" "b/src/a\\tb.snap"\n@@ -0,0 +1 @@\n+x\n'
  } >"$tmp/in.patch"

  dropped=$(strip_generated "$tmp/in.patch" "$tmp/out.patch")
  check "strip_generated exit status" 0 $?

  check "left-out list and line counts" "$(printf '%s\t%s\n' \
    src/__snapshots__/Chart.test.tsx.snap 8 \
    package-lock.json 9 \
    web/pnpm-lock.yaml 6 \
    __snapshots__/root.txt 6 \
    crates/x/Cargo.lock 6 \
    go.sum 6 \
    src/Old.snap 6 \
    'src/a\tb.snap' 3)" "$dropped"

  check "kept files" "$(printf '%s\n' src/app.ts src/snapshot.ts docs/yarn.lock.md src/Name.ts)" \
    "$(sed -n 's|^diff --git a/.* b/||p' "$tmp/out.patch")"

  check "kept hunks are whole" "$({ hunk src/app.ts src/app.ts 2; hunk src/snapshot.ts src/snapshot.ts 1; hunk docs/yarn.lock.md docs/yarn.lock.md 1; hunk old/Name.snap src/Name.ts 1; })" \
    "$(cat "$tmp/out.patch")"

  hunk yarn.lock yarn.lock 2 >"$tmp/only.patch"
  dropped=$(strip_generated "$tmp/only.patch" "$tmp/only.out")
  check "only generated: listed" "$(printf 'yarn.lock\t7')" "$dropped"
  check "only generated: empty patch" "0" "$(wc -c <"$tmp/only.out" | tr -d ' ')"

  hunk src/a.ts src/a.ts 1 >"$tmp/none.patch"
  dropped=$(strip_generated "$tmp/none.patch" "$tmp/none.out")
  check "nothing generated: nothing listed" "" "$dropped"
  check "nothing generated: patch unchanged" "$(cat "$tmp/none.patch")" "$(cat "$tmp/none.out")"

  exit "$fail"
)

run_sections_parallel section_1 section_2 section_3 section_4
exit $?
