#!/usr/bin/env bash
# Consolidated diff, classification, history budget, and size-ceiling tests for
# auto-review (upstream issue).
# Consolidates:
#   - test-auto-review-classify.sh
#   - test-auto-review-collect-history.sh
#   - test-auto-review-size-ceiling.sh
#   - test-auto-review-strip-generated.sh
set -u
here=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck disable=SC1091 # sourced for its functions; checked on its own
. "$here/auto-review.sh"
# shellcheck disable=SC1091
. "$here/tests/lib-parallel.sh"
set +e

check() { # $1 = label, $2 = want, $3 = got
  if [ "$2" = "$3" ]; then
    printf 'ok    %s\n' "$1"
  else
    printf 'FAIL  %s\n--- want\n%s\n--- got\n%s\n' "$1" "$2" "$3"
    fail=1
  fi
}

check_match() { # $1 = label, $2 = line pattern (ERE), $3 = text
  if printf '%s\n' "$3" | grep -Eq -- "$2"; then
    printf 'ok    %s\n' "$1"
  else
    printf 'FAIL  %s\n--- pattern\n%s\n--- got\n%s\n' "$1" "$2" "$3"
    fail=1
  fi
}

# ==============================================================================
# Section 1: File classification, scope check, reading plan, rename detection
# ==============================================================================
section_1() (
  fixtures=$(mktemp -d)
  trap 'rm -rf "$fixtures"' EXIT
  fail=0

  hunk() { # $1 = path, $2 = body lines; a patch section of $2 + 5 lines
    printf 'diff --git a/%s b/%s\nindex 1111111..2222222 100644\n--- a/%s\n+++ b/%s\n@@ -1 +1,%d @@\n' "$1" "$1" "$1" "$1" "$2"
    local i
    for i in $(seq "$2"); do printf '+line %d\n' "$i"; done
  }

  kind_of() { # $1 = path; the kind a one-file patch for it gets
    hunk "$1" 1 >"$fixtures/one.patch"
    classify_paths "$fixtures/one.patch" | cut -f2
  }

  # --- every kind, by name ---------------------------------------------------
  for path in src/app.ts lib/core.sh main.go README_not.c; do check "source: $path" source "$(kind_of "$path")"; done
  for path in src/app.test.ts src/a.spec.tsx src/__tests__/a.ts tests/a.py pkg/a_test.go test_a.py; do check "tests: $path" tests "$(kind_of "$path")"; done
  for path in package-lock.json web/yarn.lock pnpm-lock.yaml go.sum Cargo.lock src/a.snap src/__snapshots__/a.txt; do check "generated: $path" generated "$(kind_of "$path")"; done
  for path in README.md docs/guide.md notes.txt guide.rst a/b/page.mdx; do check "docs: $path" docs "$(kind_of "$path")"; done
  for path in .github/workflows/check.yml Dockerfile Dockerfile.dev docker-compose.yml deploy/compose.prod.yaml pyproject.toml tox.ini .claude/settings.json package.json Makefile hooks/pre-push; do check "config: $path" config "$(kind_of "$path")"; done
  for path in db/migrations/0001_init.py prisma/schema.prisma api/v1.proto queries/report.sql; do check "migrations: $path" migrations "$(kind_of "$path")"; done
  for path in vendor/lib/a.js third_party/x/y.c web/jquery.min.js; do check "vendored: $path" vendored "$(kind_of "$path")"; done

  # --- precedence: the name decides in this order -----------------------------
  check "a lockfile under vendor/ is generated" generated "$(kind_of vendor/pkg/yarn.lock)"
  check "a workflow under a tests directory is config" config "$(kind_of tests/.github/workflows/x.yml)"
  check "docs under tests/ are tests" tests "$(kind_of tests/README.md)"

  # --- from the patch, not the name -------------------------------------------
  {
    printf 'diff --git a/old/name.ts b/new/name.ts\nsimilarity index 100%%\nrename from old/name.ts\nrename to new/name.ts\n'
    printf 'diff --git a/src/b.ts b/src/c.ts\nsimilarity index 80%%\nrename from src/b.ts\nrename to src/c.ts\nindex 1..2 100644\n--- a/src/b.ts\n+++ b/src/c.ts\n@@ -1 +1,2 @@\n+x\n'
    printf 'diff --git a/logo.png b/logo.png\nnew file mode 100644\nindex 0000000..1111111\nBinary files /dev/null and b/logo.png differ\n'
    printf 'diff --git a/tool b/tool\nnew file mode 100755\nindex 0000000..1111111\nGIT binary patch\nliteral 3\nKcmZQz00000\n\n'
  } >"$fixtures/mixed.patch"
  check "a pure rename, a rename with edits, two binary files" \
    "new/name.ts	renamed	4
src/c.ts	source	9
logo.png	binary	4
tool	binary	7" \
    "$(classify_paths "$fixtures/mixed.patch")"

  # --- lines per file and the order of the patch -----------------------------
  { hunk src/a.ts 3; hunk tests/t.py 10; hunk README.md 1; } >"$fixtures/lines.patch"
  check "one row per file, with its lines, in patch order" \
    "src/a.ts	source	8
tests/t.py	tests	15
README.md	docs	6" \
    "$(classify_paths "$fixtures/lines.patch")"

  # --- vendored and generated by the repository's own marks ------------------
  printf 'third/lib.c\n' >"$fixtures/vendored.txt"
  { hunk third/lib.c 1; hunk src/app.ts 1; } >"$fixtures/v.patch"
  check "a path the base marks linguist-vendored is vendored" \
    "third/lib.c	vendored	6
src/app.ts	source	6" \
    "$(classify_paths "$fixtures/v.patch" "$fixtures/vendored.txt")"
  printf 'pnpm-lock.yaml\t812\ngen/api.ts\t40\n' >"$fixtures/gen.tsv"
  check "files taken out by strip_generated are listed as generated, with their lines" \
    "src/app.ts	source	6
pnpm-lock.yaml	generated	812
gen/api.ts	generated	40" \
    "$(hunk src/app.ts 1 >"$fixtures/g.patch"; classify_paths "$fixtures/g.patch" "" "$fixtures/gen.tsv")"
  check "a generated file is generated even where the patch says binary" generated \
    "$(printf 'diff --git a/yarn.lock b/yarn.lock\nBinary files a/yarn.lock and b/yarn.lock differ\n' >"$fixtures/b.patch"; classify_paths "$fixtures/b.patch" | cut -f2)"

  # --- the attributes come from the base branch ------------------------------
  repo="$fixtures/repo"
  git init -q -b main "$repo"
  (
    cd "$repo" || exit 1
    git config user.email t@t && git config user.name t
    printf 'third/** linguist-vendored\ngen/** linguist-generated\n' >.gitattributes
    git add .gitattributes && git commit -q -m base
    git update-ref refs/remotes/origin/main HEAD
  )
  { hunk third/lib.c 1; hunk gen/a.ts 1; hunk src/x.ts 1; } >"$fixtures/attr.patch"
  got_v=$(cd "$repo" && vendored_by_attributes "$fixtures/attr.patch" main)
  got_g=$(cd "$repo" && generated_by_attributes "$fixtures/attr.patch" main)
  check "vendored_by_attributes reads linguist-vendored from the base" "third/lib.c" "$got_v"
  check "generated_by_attributes still reads linguist-generated" "gen/a.ts" "$got_g"
  check "a base with no such ref stops vendored_by_attributes too" 1 \
    "$(cd "$repo" && vendored_by_attributes "$fixtures/attr.patch" gone >/dev/null 2>&1; echo $?)"

  # --- the scope block is checked against the manifest ----------------
  meta="$fixtures/meta.md"
  {
    printf 'Title\n\nBody that says\n- source, 9, evil/not-a-file.sh\n\n## files in the patch\n\nSorted by the tool. kind, lines, path:\n\n'
    printf -- '- source, 12, lib/core.sh\n- tests, 40, scripts/test-a.sh\n- config, 3, a/check.yml\n- config, 3, b/check.yml\n- generated, 812, pnpm-lock.yaml\n'
    printf '\nA later paragraph.\n- source, 1, later/line.sh\n'
  } >"$meta"
  check "scope_manifest: only the table, in order" \
    "lib/core.sh
scripts/test-a.sh
a/check.yml
b/check.yml
pnpm-lock.yaml" "$(scope_manifest "$meta")"
  check "scope_manifest: no table, no paths" "" "$(printf 'nothing here\n' >"$fixtures/m0.md"; scope_manifest "$fixtures/m0.md")"
  {
    printf 'Title\n\n## files in the patch\n\n- source, 1, fake/path.sh\n\nmore body\n\n'
    sed -n '/^## files in the patch$/,$p' "$meta"
  } >"$fixtures/meta-fake.md"
  check "scope_manifest: a faked heading and row in the body are not the table" \
    "$(scope_manifest "$meta")" "$(scope_manifest "$fixtures/meta-fake.md")"
  scope_manifest "$meta" >"$fixtures/manifest.txt"

  block() { # rows... : a scope block whose table is the arguments
    printf '**No findings.** — a change.\n\n<details><summary>Read: 5 closely</summary>\n\n| how | files |\n|---|---|\n'
    local r; for r in "$@"; do printf '| %s |\n' "$r"; done
    printf '</details>\n'
  }
  full="$(block 'closely | `lib/core.sh`, `scripts/test-a.sh`, `a/check.yml`, `b/check.yml`' 'not read | `pnpm-lock.yaml` (generated)')"
  printf '%s\n' "$full" >"$fixtures/r-full.md"
  check "scope_check: every path named, review unchanged" "$full" "$(scope_check "$fixtures/r-full.md" "$fixtures/manifest.txt")"

  short="$(block 'closely | `core.sh`, `test-a.sh`, `a/check.yml`, `b/check.yml`' 'not read | `pnpm-lock.yaml`')"
  printf '%s\n' "$short" >"$fixtures/r-short.md"
  check "scope_check: a file name alone counts when it is unique" "$short" "$(scope_check "$fixtures/r-short.md" "$fixtures/manifest.txt")"

  amb="$(block 'closely | `lib/core.sh`, `scripts/test-a.sh`, `check.yml`' 'not read | `pnpm-lock.yaml`')"
  printf '%s\n' "$amb" >"$fixtures/r-amb.md"
  got="$(scope_check "$fixtures/r-amb.md" "$fixtures/manifest.txt")"
  check_match "scope_check: a name two paths share does not count for either" '^\| not accounted for \| `a/check\.yml`, `b/check\.yml` \|$' "$got"

  miss="$(block 'closely | `lib/core.sh`' 'skimmed | `scripts/test-a.sh`')"
  printf '%s\n' "$miss" >"$fixtures/r-miss.md"
  got="$(scope_check "$fixtures/r-miss.md" "$fixtures/manifest.txt")"
  check_match "scope_check: missing paths are added to the block as not accounted for" '^\| not accounted for \| `a/check\.yml`, `b/check\.yml`, `pnpm-lock\.yaml` \|$' "$got"
  check_match "scope_check: ... inside the block, the last row before its end" '^\| not accounted for ' "$(printf '%s\n' "$got" | grep -B1 '^</details>$' | head -1)"
  check_match "scope_check: ... and the summary says how many" 'Read: 5 closely · 3 not accounted for</summary>' "$got"
  check_match "scope_check: the verdict line is still the first line" '^\*\*No findings\.\*\* — a change\.' "$got"

  printf '**1 finding.** — x\n\n1. `lib/core.sh:3` bad\n' >"$fixtures/r-none.md"
  got="$(scope_check "$fixtures/r-none.md" "$fixtures/manifest.txt")"
  check_match "scope_check: no block at all, a block is added with every path" '<details><summary>Read: scope block missing' "$got"
  check_match "scope_check: ... and lists them all, the findings kept" '\| not accounted for \| `lib/core\.sh`, `scripts/test-a\.sh`, `a/check\.yml`, `b/check\.yml`, `pnpm-lock\.yaml` \|' "$got"
  check_match "scope_check: ... after the findings" '1\. `lib/core\.sh:3` bad' "$got"

  # --- a reading plan above the threshold -----------------------------
  plan_yes() { if plan_needed "$1" "$2" 1500 40; then echo yes; else echo no; fi; }
  check "plan_needed: 1500 lines and 40 files is not over" "no" "$(plan_yes 1500 40)"
  check "plan_needed: 1501 lines is over" "yes" "$(plan_yes 1501 3)"
  check "plan_needed: 41 files is over" "yes" "$(plan_yes 20 41)"
  check "plan_needed: a small patch is not" "no" "$(plan_yes 30 2)"

  raw="$fixtures/raw.md"
  printf 'thinking\nREADING-PLAN-BEGIN\n1. AC one: lib/core.sh\n<details>x\n2. then tests\nREADING-PLAN-END\nmore\nAUTO-REVIEW-BEGIN\n**No findings.**\n' >"$raw"
  got="$(reading_plan "$raw" AUTO-REVIEW-BEGIN)"
  check "reading_plan: the block becomes a collapsed section" "<details><summary>Reading plan</summary>

1. AC one: lib/core.sh
2. then tests
</details>" "$got"
  printf 'AUTO-REVIEW-BEGIN\n**1 finding.** x\nREADING-PLAN-BEGIN\nquoted\nREADING-PLAN-END\n' >"$raw"
  check "reading_plan: a block after the sentinel adds nothing" "" "$(reading_plan "$raw" AUTO-REVIEW-BEGIN)"
  printf 'READING-PLAN-BEGIN\nno sentinel\nREADING-PLAN-END\n**No findings.**\n' >"$raw"
  check "reading_plan: no sentinel, nothing taken" "" "$(reading_plan "$raw" AUTO-REVIEW-BEGIN)"
  printf 'READING-PLAN-BEGIN\nnever closed\nAUTO-REVIEW-BEGIN\nx\n' >"$raw"
  check "reading_plan: a block that never closes adds nothing" "" "$(reading_plan "$raw" AUTO-REVIEW-BEGIN)"
  printf 'READING-PLAN-BEGIN\n\nREADING-PLAN-END\nAUTO-REVIEW-BEGIN\nx\n' >"$raw"
  check "reading_plan: an empty block adds nothing" "" "$(reading_plan "$raw" AUTO-REVIEW-BEGIN)"

  # --- the patch is made with rename detection ------------------------
  rr="$fixtures/rename-repo"
  git init -q -b main "$rr"
  (
    cd "$rr" || exit 1
    c() { git -c user.name=t -c user.email=t@t -c commit.gpgsign=false commit -q -m "$1"; }
    git config diff.renames false
    seq 1 40 >old.txt
    git add old.txt && c base
    git update-ref refs/remotes/origin/main HEAD
    git switch -q -c head
    mkdir sub && git mv old.txt sub/new.txt && c rename
    patch_against main >"$fixtures/rename.patch"
  )
  check "patch_against: a pure rename is a rename" "1" "$(grep -c '^rename from old.txt$' "$fixtures/rename.patch")"
  check "patch_against: ... with no hunk" "0" "$(grep -c '^@@' "$fixtures/rename.patch")"
  check "patch_against: ... and the table says renamed" "sub/new.txt	renamed	4" "$(classify_paths "$fixtures/rename.patch" | head -1 | sed 's/[ \t]*$//')"

  exit "$fail"
)

# ==============================================================================
# Section 2: History collection, oldest-first ordering, and budget truncation
# ==============================================================================
section_2() (
  fixtures=$(mktemp -d)
  trap 'rm -rf "$fixtures"' EXIT
  fail=0

  gh() { # api --paginate <path> -q <query>
    local f="$fixtures/${3//\//_}"
    if [ -f "$f" ]; then cat "$f"; fi
  }

  entry() { # $1 = api path, $2 = when, $3 = header, $4 = body
    printf '%s\t%s\t%s\n' "$2" "$3" "$(printf '%s' "$4" | base64 | tr -d '\n')" >>"$fixtures/${1//\//_}"
  }

  headers() { # $1 = history file
    sed -n 's/^## //p' "$1"
  }

  entry repos/o/r/pulls/1/reviews 2026-11-04T10:00:00Z 'review by a, against 1111111' 'first'
  entry repos/o/r/pulls/1/reviews 2026-11-04T13:00:00Z 'review by a, against 2222222' 'fourth'
  entry repos/o/r/pulls/1/comments 2026-11-04T12:00:00Z 'comment by b, on x.sh' 'third'
  entry repos/o/r/issues/1/comments 2026-11-04T11:00:00Z 'comment by b' 'second'

  said=$(collect_history o/r 1 "$fixtures/1.md" 2>&1)
  check "collect_history exit status" 0 $?
  check "fits the budget: nothing logged" "" "$said"
  check "fits the budget: every entry, oldest first" "$(printf '%s\n' \
    '[HUMAN] review by a, against 1111111, 2026-11-04T10:00:00Z' \
    '[HUMAN] comment by b, 2026-11-04T11:00:00Z' \
    '[HUMAN] comment by b, on x.sh, 2026-11-04T12:00:00Z' \
    '[HUMAN] review by a, against 2222222, 2026-11-04T13:00:00Z')" "$(headers "$fixtures/1.md")"
  check "fits the budget: bodies decoded" "$(printf '%s\n' first second third fourth)" \
    "$(grep -E '^(first|second|third|fourth)$' "$fixtures/1.md")"

  long=$(printf '%8000s' '' | tr ' ' x)
  for i in 01 02 03 04 05 06 07 08 09 10; do
    entry repos/o/r/pulls/2/reviews "2026-11-04T10:$i:00Z" "review $i" "$long"
  done
  entry repos/o/r/issues/2/comments 2026-11-04T11:01:00Z 'answer 11' 'no'
  entry repos/o/r/issues/2/comments 2026-11-04T11:02:00Z 'answer 12' 'no'

  said=$(collect_history o/r 2 "$fixtures/2.md" 2>&1)
  check "exit status over budget" 0 $?
  check "over budget: logged" '#2: discussion is 12 entries — giving the reviewer the 9 most recent' \
    "$(printf '%s\n' "$said" | sed 's/^\[[^]]*\] //')"
  check "over budget: says what was left out" '_The 3 oldest entries were left out; these are the 9 most recent._' \
    "$(head -n 1 "$fixtures/2.md")"
  check "over budget: the newest kept" "$(printf '%s\n' \
    '[HUMAN] review 04, 2026-11-04T10:04:00Z' '[HUMAN] review 05, 2026-11-04T10:05:00Z' \
    '[HUMAN] review 06, 2026-11-04T10:06:00Z' '[HUMAN] review 07, 2026-11-04T10:07:00Z' \
    '[HUMAN] review 08, 2026-11-04T10:08:00Z' '[HUMAN] review 09, 2026-11-04T10:09:00Z' \
    '[HUMAN] review 10, 2026-11-04T10:10:00Z' \
    '[HUMAN] answer 11, 2026-11-04T11:01:00Z' '[HUMAN] answer 12, 2026-11-04T11:02:00Z')" "$(headers "$fixtures/2.md")"

  said=$(collect_history o/r 3 "$fixtures/3.md" 2>&1)
  check "no discussion: exit status" 0 $?
  check "no discussion: nothing logged" "" "$said"
  check "no discussion: empty file" "0" "$(wc -c <"$fixtures/3.md" | tr -d ' ')"

  entry repos/o/r/pulls/4/reviews 2026-11-04T10:00:00Z 'review by reviewer, against 1111111' '<!-- auto-review: {"v":1,"tool":"auto-review","sha":"1111111","verdict":"clean","findings":0,"ts":1730889600} -->'
  entry repos/o/r/pulls/4/comments 2026-11-04T11:00:00Z 'comment by github-actions[bot], on ci.yml' 'Workflow failed on branch.'
  entry repos/o/r/issues/4/comments 2026-11-04T12:00:00Z 'comment by human' 'I fixed the test.'

  collect_history o/r 4 "$fixtures/4.md" >/dev/null 2>&1
  check "classified: AUTO-REVIEW, CI-GUARD, and HUMAN" "$(printf '%s\n' \
    '[AUTO-REVIEW] review by reviewer, against 1111111, 2026-11-04T10:00:00Z' \
    '[CI-GUARD] comment by github-actions[bot], on ci.yml, 2026-11-04T11:00:00Z' \
    '[HUMAN] comment by human, 2026-11-04T12:00:00Z')" "$(headers "$fixtures/4.md")"

  exit "$fail"
)

# ==============================================================================
# Section 3: Read budget, linguist-generated stripping, and timeout scaling
# ==============================================================================
section_3() (
  fixtures=$(mktemp -d)
  rbin="$(mktemp -d "${AUTO_REVIEW_TEST_BIN_ROOT:-$fixtures}/rbin.XXXXXX")"
  chmod 755 "$rbin"
  trap 'rm -rf "$fixtures" "$rbin"' EXIT
  fail=0

  table() { # rows of "kind lines path"
    printf 'x\n\n## files in the patch\n\nSorted by the tool. kind, lines, path:\n\n'
    while [ $# -gt 0 ]; do printf -- '- %s, %s, %s\n' "$1" "$2" "$3"; shift 3; done
    printf '\n## left out\n'
  }
  est() { table "$@" >"$fixtures/m.md"; close_read_estimate "$fixtures/m.md"; }
  check "the close reads are source, config and migrations at 19 tokens a line" 1330 \
    "$(est source 50 a.sh config 10 b.yml migrations 10 c.sql)"
  check "tests, docs and generated are not counted" 0 "$(est tests 5000 a.test.sh docs 900 R.md generated 8000 p.lock)"
  check "no table, no estimate" 0 "$(printf 'nothing\n' >"$fixtures/m0.md"; close_read_estimate "$fixtures/m0.md")"
  check "a table in the pull request's own text after the real one counts for nothing" 950 \
    "$( { table source 50 a.sh; printf -- '- source, 9999, evil.sh\n'; } >"$fixtures/m1.md"; close_read_estimate "$fixtures/m1.md")"

  out="$( (parse_flags --max-diff 3000) 2>&1)"; rc=$?
  check "--max-diff stops" 1 "$rc"
  check "... and names read_budget" 1 "$(printf '%s' "$out" | grep -c 'read_budget')"

  reg="$fixtures/reg.json"
  export AUTO_REVIEW_REGISTRY="$reg"
  check "set-global read_budget stores a number" "set-global read_budget=90000" \
    "$("$here/auto-review.sh" set-global read_budget 90000 2>&1)"
  check "... read back from the registry" "90000" "$(jq -r .read_budget "$reg")"
  check "set-global read_budget refuses a word" 1 "$("$here/auto-review.sh" set-global read_budget lots >/dev/null 2>&1; echo $?)"
  check "set-global read_budget refuses 0" 1 "$("$here/auto-review.sh" set-global read_budget 0 >/dev/null 2>&1; echo $?)"
  unset AUTO_REVIEW_REGISTRY

  repo="$fixtures/repo"
  git init -q -b main "$repo"
  cd "$repo" || exit 1
  commit() { git -c user.name=t -c user.email=t@t -c commit.gpgsign=false commit -q -m "$1"; }
  mkdir -p gen api src nested
  printf 'gen/** linguist-generated=true\napi/schema.json linguist-generated\ngen/kept.ts -linguist-generated\n' >.gitattributes
  printf '*.pb.ts linguist-generated=true\n' >nested/.gitattributes
  printf '1\n' | tee gen/client.ts gen/kept.ts api/schema.json nested/a.pb.ts src/app.ts src/sneaky.ts 'src/a b.ts' >/dev/null
  git add -A && commit base
  git update-ref refs/remotes/origin/main HEAD
  git switch -q -c head
  printf '2\n' | tee gen/client.ts gen/kept.ts api/schema.json nested/a.pb.ts src/app.ts src/sneaky.ts 'src/a b.ts' >/dev/null
  printf 'src/sneaky.ts linguist-generated=true\n' >>.gitattributes
  git add -A && commit head
  git diff origin/main...HEAD >"$fixtures/in.patch"

  marked=$(generated_by_attributes "$fixtures/in.patch" main)
  check "generated_by_attributes exit status" 0 $?
  check "marked on the base branch, not on the head" "$(printf '%s\n' api/schema.json gen/client.ts nested/a.pb.ts)" \
    "$(printf '%s\n' "$marked" | sort)"

  printf '%s\n' "$marked" >"$fixtures/marked"
  dropped=$(strip_generated "$fixtures/in.patch" "$fixtures/out.patch" "$fixtures/marked")
  check "left out and listed" "$(printf '%s\n' api/schema.json gen/client.ts nested/a.pb.ts)" \
    "$(printf '%s\n' "$dropped" | cut -f1 | sort)"
  check "the rest stays, .gitattributes included" "$(printf '%s\n' .gitattributes gen/kept.ts 'src/a b.ts' src/app.ts src/sneaky.ts)" \
    "$(patch_lines_per_file "$fixtures/out.patch" | cut -f1 | sort)"

  check "a base with no such ref stops the tick" 1 "$(generated_by_attributes "$fixtures/in.patch" gone >/dev/null 2>&1; echo $?)"

  check "reviewer_timeout: 500 lines, no plan -> base (900)" 900 \
    "$(reviewer_timeout 500 0 900 1500 2>/dev/null)"
  check "reviewer_timeout: 1500 lines (at threshold), no plan -> base (900)" 900 \
    "$(reviewer_timeout 1500 0 900 1500 2>/dev/null)"
  check "reviewer_timeout: 500 lines, plan=1 -> at least 2*base (1800)" 1800 \
    "$(reviewer_timeout 500 1 900 1500 2>/dev/null)"
  check "reviewer_timeout: 10000 lines, plan=0 -> scales above over (3450)" 3450 \
    "$(reviewer_timeout 10000 0 900 1500 2>/dev/null)"
  check "reviewer_timeout: 20000 lines, plan=1 -> capped at 4*base (3600)" 3600 \
    "$(reviewer_timeout 20000 1 900 1500 2>/dev/null)"
  check "reviewer_timeout: defaults (500 lines) -> 900" 900 \
    "$(reviewer_timeout 500 2>/dev/null)"
  check "reviewer_timeout: defaults (10000 lines) -> 3450" 3450 \
    "$(reviewer_timeout 10000 2>/dev/null)"

